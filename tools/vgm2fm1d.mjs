// A Mega Drive VGM (or .vgz) to an FM1-TRAX song, from the command line: web/vgmimport.js, the
// converter the editor's Import VGM runs, with the DAC kit from web/fm1trax.wasm (host/build_web.sh).
//   node tools/vgm2fm1d.mjs IN.vgm OUT.fm1d [--title T] [--author A] [--dac N=DRUM]... [--rows R]
//   node tools/vgm2fm1d.mjs IN.vgm --header OUT.h ...   the song as a C array, DEMO_SONG
import {readFileSync, writeFileSync} from "node:fs";
import {gunzipSync} from "node:zlib";
import {importVgm} from "../web/vgmimport.js";

const args = process.argv.slice(2), opt = {dac: {}}, files = [];
let header = null;
for (let k = 0; k < args.length; k++) {
    const a = args[k];
    if (a === "--title") opt.title = args[++k];
    else if (a === "--author") opt.author = args[++k];
    else if (a === "--rows") opt.rows = +args[++k];
    else if (a === "--header") header = args[++k];
    else if (a === "--dac") { const [n, d] = args[++k].split("="); opt.dac[+n] = d; }
    else files.push(a);
}
if (!files.length || (!header && files.length < 2)) {
    console.error("usage: node tools/vgm2fm1d.mjs IN.vgm OUT.fm1d|--header OUT.h [--title T] [--author A] [--dac N=DRUM] [--rows R]");
    process.exit(2);
}
let bytes = readFileSync(files[0]);
if (bytes[0] === 0x1F && bytes[1] === 0x8B) bytes = gunzipSync(bytes);

// the kit, from the engine
const url = new URL("../web/fm1trax.wasm", import.meta.url);
const x = (await WebAssembly.instantiate(readFileSync(url), {})).instance.exports;
x.web_ed_init();
const cstr = p => { const m = new Uint8Array(x.memory.buffer); let s = ""; while (m[p]) s += String.fromCharCode(m[p++]); return s; };
opt.kit = Array.from({length: x.web_sample_count()}, (_, i) => ({
    name: cstr(x.web_sample_name(i)),
    data: new Uint8Array(x.memory.buffer, x.web_sample_data(i), x.web_sample_len(i)).slice(),
    rate: x.web_sample_rate(i),
}));

let r;
try {
    r = importVgm(new Uint8Array(bytes), opt);
} catch (err) {
    for (const n of err.notes || []) console.error(n);
    console.error(err.message);
    process.exit(1);
}
for (const n of r.notes) console.error(n);
const i = r.info;
console.error(`"${i.title}" by ${i.author}: ${i.orders} orders, ${i.rows} rows, ${i.instruments} instruments, ` +
    `${i.patternRows} pattern rows, ${i.seconds.toFixed(1)} s`);
console.error("pitch match: " + Object.entries(i.match).map(([c, m]) => `${c} ${(m * 100).toFixed(0)}%`).join(", "));

// the song reads back in the engine
new Uint8Array(x.memory.buffer, x.web_io(), r.song.length).set(r.song);
if (x.web_song_read(r.song.length) !== 0) {
    console.error("the engine does not read the song back");
    process.exit(1);
}
if (header) {
    const hex = Array.from(r.song, b => "0x" + b.toString(16).padStart(2, "0"));
    const lines = [];
    for (let k = 0; k < hex.length; k += 16) lines.push("    " + hex.slice(k, k + 16).join(", ") + ",");
    writeFileSync(header, `/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/vgm2fm1d.mjs from ${files[0].split("/").pop()}: do not edit */\n` +
        `#pragma once\n#include <stdint.h>\n\nstatic const uint8_t DEMO_SONG[${r.song.length}] = {\n${lines.join("\n")}\n};\n`);
} else
    writeFileSync(files[1], r.song);
console.error(`${r.song.length} bytes`);
